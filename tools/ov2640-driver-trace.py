#!/usr/bin/env python3
"""Generate SCCB fixtures by compiling selected, unchanged v2.1.4 driver routines.
Network and a C compiler are needed only to regenerate, not to run Rust tests.
Run from repository root; all downloads/builds stay in caller-provided scratch.
"""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess
import urllib.request

REV = 'b817e9b81041980608d1a3d3e0b08d86e3666382'
SOURCES = ['sensors/ov2640.c', 'sensors/private_include/ov2640_regs.h',
           'sensors/private_include/ov2640_settings.h', 'driver/sensor.c', 'driver/sccb.c']


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--scratch', required=True, type=Path)
    parser.add_argument('--check', action='store_true', help='compare generated bytes without changing fixtures')
    args = parser.parse_args()
    scratch = args.scratch.resolve()
    scratch.mkdir(parents=True, exist_ok=True)
    manifest = {}
    for source in SOURCES:
        url = f'https://raw.githubusercontent.com/espressif/esp32-camera/{REV}/{source}'
        data = urllib.request.urlopen(url).read()
        (scratch / Path(source).name).write_bytes(data)
        manifest[source] = {'url': url, 'sha256': hashlib.sha256(data).hexdigest(), 'bytes': len(data)}
    (scratch / 'esp_attr.h').write_text('#define DRAM_ATTR\n')
    driver = (scratch / 'ov2640.c').read_text()
    # Exact source span: bank access, reset, pixformat, window and framesize.
    routines = driver[driver.index('static volatile ov2640_bank_t'):driver.index('static int set_contrast')]
    detect = driver[driver.index('int esp32_camera_ov2640_detect'):driver.index('int esp32_camera_ov2640_init')]
    harness = r'''
#include <stdint.h>
#include <stdio.h>
#include <stdlib.h>
#include "ov2640_settings.h"
#define ESP_LOGI(...) ((void)0)
#define portTICK_PERIOD_MS 1
#define CONFIG_IDF_TARGET_ESP32 1
#define OV2640_SCCB_ADDR 0x30
#define OV2640_PID 0x26
#define vTaskDelay(x) ((void)(x))
typedef enum { PIXFORMAT_RGB565, PIXFORMAT_RGB888, PIXFORMAT_YUV422, PIXFORMAT_GRAYSCALE, PIXFORMAT_JPEG } pixformat_t;
// Selected 4:3 entries of public sensor.c:resolution; intermediate CIF/SVGA
// enum entries retain the original set_framesize mode-selection thresholds.
typedef enum { FRAMESIZE_QQVGA, FRAMESIZE_CIF, FRAMESIZE_VGA, FRAMESIZE_SVGA, FRAMESIZE_UXGA } framesize_t;
static const struct { int width, height, aspect_ratio; } resolution[] = {
    {160,120,0}, {400,296,0}, {640,480,0}, {800,600,0}, {1600,1200,0}
};
typedef int aspect_ratio_t;
typedef struct { int slv_addr; pixformat_t pixformat; struct { framesize_t framesize; } status; } sensor_t;
typedef struct { int PID, VER, MIDL, MIDH; } sensor_id_t;
int SCCB_Write(int address, uint8_t reg, uint8_t value) {
    if (address != 0x30) abort();
    printf("W %02x %02x\n", reg, value); return 0;
}
int SCCB_Read(int address, uint8_t reg) {
    if (address != 0x30) abort();
    int value = reg == 0x0a ? 0x26 : reg == 0x0b ? 0x42 : reg == 0x1c ? 0x7f : 0xa2;
    printf("R %02x %02x\n", reg, value); return value;
}
'''
    main_c = r'''
int main(int argc, char **argv) {
    if (argc != 2) return 1;
    sensor_t sensor = {.slv_addr=0x30, .pixformat=PIXFORMAT_RGB565};
    sensor_id_t id;
    if (esp32_camera_ov2640_detect(0x30, &id) != 0x26) return 2;
    // The real detect routine does not update the driver's cached bank.
    if (reset(&sensor)) return 3;
    if (argv[1][0] == 'r') return 0;
    sensor.pixformat = argv[1][1] == 'r' ? PIXFORMAT_RGB565 : argv[1][1] == 'j' ? PIXFORMAT_JPEG : PIXFORMAT_YUV422;
    framesize_t size = argv[1][0] == 'q' ? FRAMESIZE_QQVGA : argv[1][0] == 'v' ? FRAMESIZE_VGA : FRAMESIZE_UXGA;
    return set_framesize(&sensor, size);
}
'''
    (scratch / 'trace.c').write_text(harness + routines + detect + main_c)
    subprocess.run(['cc', '-std=c11', '-I', str(scratch), str(scratch / 'trace.c'), '-o', str(scratch / 'trace')], check=True)
    out = Path('esp-soc/tests/fixtures/ov2640')
    out.mkdir(parents=True, exist_ok=True)
    def emit(name, data):
        path = out / name
        if args.check:
            assert path.read_bytes() == data, f'fixture mismatch: {path}'
        else:
            path.write_bytes(data)

    for name, mode in [('reset', 'reset'), ('qqvga-rgb565', 'qr'), ('vga-rgb565', 'vr'),
                       ('qqvga-yuv422', 'qy'), ('vga-jpeg', 'vj'), ('uxga-rgb565', 'ur')]:
        data = subprocess.check_output([str(scratch / 'trace'), mode])
        emit(f'{name}.txt', data)
    emit('sources.json', (json.dumps(manifest, indent=2) + '\n').encode())
    print('All six driver traces and source hashes match.' if args.check else 'Generated six driver traces.')


if __name__ == '__main__':
    main()
