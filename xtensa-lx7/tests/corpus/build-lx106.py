#!/usr/bin/env python3
"""Rebuild the repository-owned MIT CPU corpus; requires both assembler prefixes."""
import argparse
import hashlib
import json
from pathlib import Path
import re
import subprocess

p = argparse.ArgumentParser()
p.add_argument('--lx106-prefix', required=True)
p.add_argument('--s3-prefix', required=True)
p.add_argument('--out', type=Path, required=True, help='scratch directory')
a = p.parse_args()
a.out.mkdir(parents=True, exist_ok=True)
root = Path(__file__).resolve().parent

def run(prefix, tool, *args):
    return subprocess.check_output([prefix + tool, *map(str, args)], text=True)

versions = {name: run(prefix, 'as', '--version').splitlines()[0]
            for name, prefix in [('lx106', a.lx106_prefix), ('s3', a.s3_prefix)]}
versions['lx106_gcc'] = run(a.lx106_prefix, 'gcc', '-dumpversion').strip()
assert versions['lx106'] == 'GNU assembler (GNU Binutils) 2.32'
assert versions['lx106_gcc'] == '10.3.0'
assert versions['s3'] == 'GNU assembler (crosstool-NG esp-2021r2-patch5) 2.35.1.20201223'
obj = a.out / 'lx106.o'
elf = a.out / 'lx106.elf'
run(a.lx106_prefix, 'as', '--no-transform', '-o', obj, root / 'lx106.S')
run(a.lx106_prefix, 'ld', '--no-relax', '-Ttext=0x40100000', '-o', elf, obj)
binary = a.out / 'lx106.bin'
run(a.lx106_prefix, 'objcopy', '-O', 'binary', '-j', '.text', elf, binary)
listing = run(a.lx106_prefix, 'objdump', '-d', elf)
(root / 'lx106.dis').write_text(listing.replace(str(elf), 'lx106.elf'))

# nm's simple three-column output is independent of objdump section formatting.
symbols = {line.split()[2]: int(line.split()[0], 16) for line in run(a.lx106_prefix, 'nm', elf).splitlines() if len(line.split()) == 3}
neg = a.out / 'negative.o'
run(a.s3_prefix, 'as', '--no-transform', '-o', neg, root / 'lx106-forbidden.S')
negative_listing = run(a.s3_prefix, 'objdump', '-d', neg)
(root / 'lx106-forbidden.dis').write_text(negative_listing.replace(str(neg), 'negative.o'))
negative = []
for line in negative_listing.splitlines():
    m = re.match(r'\s*[0-9a-f]+:\s+([0-9a-f]{4,6})\s+(.+)', line)
    if m:
        if m[2].strip() == 'ill':  # section-alignment padding, not a foreign instruction
            continue
        raw = bytes.fromhex(m[1])[::-1]
        negative.append((m[2].strip(), raw))
# The LX106 assembler rejects these mnemonics; .byte is the intentional mechanism
# for feeding foreign encodings through the pinned LX106 toolchain as well.
raw_source = a.out / 'negative-lx106.S'
raw_source.write_text('.text\n' + '\n'.join('.byte ' + ','.join(str(x) for x in b) for _, b in negative) + '\n')
run(a.lx106_prefix, 'as', '-o', a.out / 'negative-lx106.o', raw_source)
run(a.lx106_prefix, 'objcopy', '-O', 'binary', '-j', '.text', a.out / 'negative-lx106.o', a.out / 'negative.bin')
assert (a.out / 'negative.bin').read_bytes() == b''.join(b for _, b in negative)
sr_negative = []
for line in (root / 'lx106-sr-forbidden.S').read_text().splitlines():
    if line.startswith('.byte '):
        data, name = line[6:].split('#', 1)
        sr_negative.append((name.strip(), bytes(int(x.strip(), 0) for x in data.split(','))))
run(a.lx106_prefix, 'as', '-o', a.out / 'sr-negative.o', root / 'lx106-sr-forbidden.S')
run(a.lx106_prefix, 'objcopy', '-O', 'binary', '-j', '.text', a.out / 'sr-negative.o', a.out / 'sr-negative.bin')
assert (a.out / 'sr-negative.bin').read_bytes() == b''.join(b for _, b in sr_negative)
program = binary.read_bytes()
text = '// Generated by build-lx106.py; repository-owned MIT fixture.\n'
text += 'pub const PROGRAM: &[u8] = &[' + ', '.join(str(x) for x in program) + '];\n'
for name in ['_start', 'done', 'leaf', 'indirect', 'arithmetic', 'literal', 'literal_insn', 'software_divide', 'divide_done', 'wait', 'return_nmi', 'return_exception', 'debug_break', 'special_registers']:
    text += f'pub const {name.upper().strip("_")}: u32 = 0x{symbols[name]:08x};\n'
text += 'pub const FORBIDDEN: &[(&str, &[u8])] = &[\n'
for name, raw in negative:
    text += f'    ({json.dumps(name)}, &[{", ".join(str(x) for x in raw)}]),\n'
text += '];\n'
text += 'pub const SR_FORBIDDEN: &[(&str, &[u8])] = &[\n'
for name, raw in sr_negative:
    text += f'    ({json.dumps(name)}, &[{", ".join(str(x) for x in raw)}]),\n'
text += '];\n'
(root / 'lx106-generated.rs').write_text(text)
manifest = {'versions': versions, 'sha256': {name: hashlib.sha256((root / name).read_bytes()).hexdigest() for name in ['build-lx106.py', 'lx106.S', 'lx106-forbidden.S', 'lx106-sr-forbidden.S', 'lx106.dis', 'lx106-forbidden.dis', 'lx106-generated.rs']}, 'program_bytes': len(program), 'forbidden_instructions': len(negative), 'sr_forbidden_instructions': len(sr_negative)}
(root / 'lx106-manifest.json').write_text(json.dumps(manifest, indent=2) + '\n')
print(json.dumps(manifest, indent=2))
